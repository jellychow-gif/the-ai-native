"""SQLite database for The AI Native.

One table `items` holds the entire pipeline state from raw scrape to published.
"""
from __future__ import annotations

import sqlite3
from pathlib import Path

DB_PATH = Path(__file__).resolve().parent.parent / "data" / "items.db"

SCHEMA = """
CREATE TABLE IF NOT EXISTS items (
    id                INTEGER PRIMARY KEY AUTOINCREMENT,
    url               TEXT    NOT NULL UNIQUE,
    title             TEXT    NOT NULL,
    source            TEXT    NOT NULL,
    source_type       TEXT    NOT NULL,
    section           TEXT,
    sub_tag           TEXT,
    hook              TEXT,
    summary           TEXT,
    implication       TEXT,
    author            TEXT,
    published_at      TEXT,
    raw_excerpt       TEXT,
    body              TEXT,
    perspective_score INTEGER,
    practice_score    INTEGER,
    frontier_score    INTEGER,
    score_reasoning   TEXT,
    status            TEXT    NOT NULL DEFAULT 'candidate',
    issue_number      INTEGER,
    scraped_at        TEXT    NOT NULL DEFAULT (datetime('now')),
    processed_at      TEXT
);

CREATE INDEX IF NOT EXISTS idx_items_status  ON items(status);
CREATE INDEX IF NOT EXISTS idx_items_section ON items(section);
CREATE INDEX IF NOT EXISTS idx_items_source  ON items(source);
"""

# Schema migrations applied to existing databases (idempotent).
# Adding a column twice raises an error; we catch and ignore it.
MIGRATIONS = [
    "ALTER TABLE items ADD COLUMN body TEXT",
    "ALTER TABLE items ADD COLUMN score_reasoning TEXT",
    "ALTER TABLE items ADD COLUMN processed_at TEXT",
    # HR sub-module classifier per PRD §6.1 — priority order per editor:
    # 组织设计 > 薪酬 > 绩效 > 员工体验 > 招聘
    "ALTER TABLE items ADD COLUMN hr_module TEXT",
    # PRD v2 §3 Intelligence Extraction — 6 structured intelligence fields
    # generated by Sonnet replace the single summary+implication. Existing
    # summary/implication stay for back-compat during migration.
    "ALTER TABLE items ADD COLUMN what_happened TEXT",
    "ALTER TABLE items ADD COLUMN why_matters TEXT",
    "ALTER TABLE items ADD COLUMN org_implication TEXT",
    "ALTER TABLE items ADD COLUMN talent_implication TEXT",
    "ALTER TABLE items ADD COLUMN hr_operating_implication TEXT",
    "ALTER TABLE items ADD COLUMN prediction TEXT",
    # 10-category classifier (PRD v2 §3 Insight Classification)
    "ALTER TABLE items ADD COLUMN insight_class TEXT",
    # Issue 化 — items get bound to a specific weekly issue at Thursday's
    # freeze. Once set, the binding is permanent so issue archives don't
    # mutate over time. NULL = not yet bound (still in candidate pool).
    "ALTER TABLE items ADD COLUMN issue_number INTEGER",
    # ANO Framework 8 dimensions (June 2026 — replaces insight_class as
    # the canonical taxonomy. insight_class column kept for backward compat
    # but ano_dimension is the displayed field.)
    "ALTER TABLE items ADD COLUMN ano_dimension TEXT",
    # Source-tier S/A/B/C — internal ranking only, never externally shown.
    "ALTER TABLE items ADD COLUMN source_tier TEXT",
]

# Issue metadata table — tracks each weekly issue's masthead info.
ISSUES_SCHEMA = """
CREATE TABLE IF NOT EXISTS issues (
    number      INTEGER PRIMARY KEY,
    date_iso    TEXT    NOT NULL,
    date_label  TEXT    NOT NULL,
    frozen_at   TEXT    NOT NULL DEFAULT (datetime('now')),
    item_count  INTEGER NOT NULL DEFAULT 0
);
"""


def get_conn() -> sqlite3.Connection:
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn


def init_db() -> None:
    with get_conn() as conn:
        conn.executescript(SCHEMA)
        conn.executescript(ISSUES_SCHEMA)
        for stmt in MIGRATIONS:
            try:
                conn.execute(stmt)
            except sqlite3.OperationalError as e:
                if "duplicate column name" in str(e):
                    continue
                raise


def upsert_item(conn: sqlite3.Connection, item: dict) -> bool:
    """Insert a new item. Returns True if inserted, False if URL already exists."""
    cols = [
        "url", "title", "source", "source_type", "section",
        "author", "published_at", "raw_excerpt", "source_tier",
    ]
    values = [item.get(c) for c in cols]
    placeholders = ",".join("?" * len(cols))
    try:
        conn.execute(
            f"INSERT INTO items ({','.join(cols)}) VALUES ({placeholders})",
            values,
        )
        return True
    except sqlite3.IntegrityError:
        return False
